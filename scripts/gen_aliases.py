#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["PyYAML>=6.0"]
# ///
"""Regenerate helium-wiki/data/aliases.yaml from wiki page aliases.

Run from the repository root during wiki generation:
    uv run scripts/gen_aliases.py

The generated YAML maps each wiki page ID to its frontmatter aliases. Entries
are sorted, duplicate aliases are removed case-insensitively, and pages without
aliases get an empty list. Headerless README/index files are ignored. Removed
pages and aliases disappear on regeneration; hand-written aliases are replaced.
Only local headers are read. No network requests are made. Paths are resolved
from this script's location. Invalid headers stop generation before writing.
Exit codes: 0 = success, 2 = invalid metadata or a filesystem error.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from gen_query import load_pages, string_list, yaml

REPO_ROOT = Path(__file__).resolve().parent.parent


def build_aliases(pages) -> dict[str, list[str]]:
    result = {}
    for page in sorted(pages, key=lambda page: (page.id.casefold(), page.id)):
        try:
            values = string_list(page.header.get("aliases"), "aliases")
        except ValueError as error:
            raise ValueError(f"{page.path}: {error}") from error
        aliases, seen = [], {page.id.casefold()}
        for value in sorted(values, key=lambda value: (value.casefold(), value)):
            key = value.casefold()
            if key not in seen:
                aliases.append(value)
                seen.add(key)
        result[page.id] = aliases
    return result


def generate(repo_root: Path = REPO_ROOT) -> Path:
    repo_root = repo_root.resolve()
    skill_root = repo_root / "helium-wiki"
    wiki_root = skill_root / "wiki"
    output = skill_root / "data" / "aliases.yaml"
    if not wiki_root.resolve().is_relative_to(skill_root) or not output.resolve().is_relative_to(skill_root):
        raise ValueError("wiki/ and data/aliases.yaml must stay inside the skill folder")
    _, pages = load_pages(wiki_root)
    aliases = build_aliases(pages)
    content = (
        "# Generated by scripts/gen_aliases.py from wiki page frontmatter.\n"
        "# Page ID -> aliases; edit the wiki pages, then regenerate this file.\n"
        + yaml.safe_dump(aliases, sort_keys=False, allow_unicode=True)
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.is_file() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8", newline="\n")
    return output


def main(argv=None) -> int:
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args(argv)
    if yaml is None:
        print("Error: PyYAML is required. Run this script with uv run.", file=sys.stderr)
        return 2
    try:
        output = generate(REPO_ROOT)
    except (OSError, UnicodeError, ValueError, yaml.YAMLError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 2
    print(output.relative_to(REPO_ROOT.resolve()).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
